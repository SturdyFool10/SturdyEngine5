    std::int32_t run_runtime(const RuntimeOptions &options,
                             const rust::Vec<rust::String> &args,
                             rust::Box<LogicHandle> logic) {
        // Strings referenced by pointer inside the engine config must outlive Runtime::run.
        const std::string window_title{options.window_title};
        const std::string app_name{options.app_name};
        const std::string app_id{options.app_id};

        SFT::Runtime::RuntimeConfig config{};
        auto &app = config.application;
        app.primary_window.title = window_title.c_str();
        app.primary_window.app_id = app_id.empty() ? nullptr : app_id.c_str();
        app.primary_window.extent = {options.width, options.height};
        app.primary_window.resizable = options.resizable;
        app.primary_window.decorated = options.decorated;
        app.primary_window.high_dpi = options.high_dpi;
        app.primary_window.mode = map(options.window_mode);
        app.primary_window.graphics_api = W::WindowGraphicsApi::Vulkan;
        app.primary_window.transparent = options.window_transparent;
        app.primary_window.visible = options.window_visible;
        if (options.has_window_position) {
            app.primary_window.position = {options.window_x, options.window_y};
            app.primary_window.use_default_position = false;
        }
        app.enable_runtime_window_management = options.runtime_window_management;
        if (options.title_update_interval_seconds > 0.0) {
            app.primary_window_title_update_interval_seconds = options.title_update_interval_seconds;
        }
        app.engine.app_name = app_name.c_str();
        app.engine.shaders_directory = std::string{options.shaders_directory};
        app.engine.features.raytracing = options.raytracing;
        app.engine.graphics_physical_device_id = std::string{options.graphics_physical_device_id};
        if (options.has_device_request) {
            SFT::Engine::DeviceRequest request;
            switch (options.device_backend) {
                case 1: request.backend = SFT::RHI::BackendType::Vulkan; break;
                case 2: request.backend = SFT::RHI::BackendType::D3D12; break;
                case 3: request.backend = SFT::RHI::BackendType::Metal; break;
                case 4: request.backend = SFT::RHI::BackendType::WebGpu; break;
                default: break; // 0 = Auto
            }
            if (!options.device_adapter_id.empty()) {
                request.adapter_id = std::string{options.device_adapter_id};
            }
            request.preference = static_cast<SFT::Engine::DevicePreference>(options.device_preference);
            app.engine.device_request = std::move(request);
        }
        app.engine.enable_shader_disk_cache = options.enable_shader_disk_cache;
        app.engine.features.prefer_async_compute = options.prefer_async_compute;
        if (options.desired_frames_in_flight != 0) {
            app.engine.features.desired_frames_in_flight = options.desired_frames_in_flight;
        }
        app.engine.features.enable_native_access_extension = options.enable_native_access;
        // Feature names -> RHI::Feature by scanning the engine's own name table; the Rust side has
        // already rejected names that don't exist.
        const auto add_features = [](const rust::Vec<rust::String> &names, SFT::RHI::FeatureSet &set) {
            for (const rust::String &name : names) {
                for (std::size_t i = 0; i < SFT::RHI::feature_count; ++i) {
                    const auto feature = static_cast<SFT::RHI::Feature>(i);
                    const char *candidate = SFT::RHI::feature_name(feature);
                    if (candidate != nullptr && std::string_view{candidate} == std::string_view{name.data(), name.size()}) {
                        set.set(feature);
                        break;
                    }
                }
            }
        };
        add_features(options.required_features, app.engine.features.required_rhi_features);
        add_features(options.optional_features, app.engine.features.optional_rhi_features);
        auto &presentation = app.engine.features.presentation;
        presentation.vsync = map(options.vsync);
        presentation.variable_refresh = map(options.variable_refresh);
        presentation.latency = map(options.latency);
        presentation.preference = map(options.preference);
        presentation.hdr_enabled = options.hdr_enabled;
        presentation.hdr_color_space = static_cast<C::HdrColorSpaceMode>(options.hdr_color_space);
        presentation.transparent_composition = options.transparent_composition;
        presentation.swapchain_image_count = options.swapchain_image_count;
        presentation.allow_present_from_compute = options.allow_present_from_compute;
        config.primary_window_title = to_ustring(options.window_title);

        SFT::Foundation::CliArgs cli;
        cli.reserve(args.size());
        for (const auto &arg : args) {
            cli.emplace_back(arg.data(), arg.size());
        }

        g_pending_logic.emplace(std::move(logic));
        const auto exit_code = SFT::Runtime::run(cli, std::move(config), &make_logic);
        g_pending_logic.reset();
        return static_cast<std::int32_t>(exit_code);
    }

