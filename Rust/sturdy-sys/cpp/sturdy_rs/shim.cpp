    bool engine_gpu_description(const EngineView &e, GpuDescription &out) {
        const auto info = e.gpu_info();
        if (!info) {
            return false;
        }
        out.name = rust::String::lossy(info->name);
        out.vendor = rust::String::lossy(info->vendor);
        out.driver_version = rust::String::lossy(info->driver_version);
        out.api_version = rust::String::lossy(info->api_version);
        out.device_type = rust::String::lossy(info->device_type);
        out.vendor_id = info->vendor_id;
        out.device_id = info->device_id;
        return true;
    }

