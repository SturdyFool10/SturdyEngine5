        UString to_ustring(const rust::String &text) {
            const std::string_view view{text.data(), text.size()};
            if (auto converted = UString::try_from_utf8(view)) {
                return std::move(*converted);
            }
            return UString{};
        }

        /// One camera per surface, persisted across frames so its temporal history (previous
        /// view-projection) survives: each frame starts from the last committed camera, gets the
        /// requested state applied over it, is handed to the renderer, then commits itself as the
        /// next frame's history — the same sequence the engine's own demo game logic runs.
        E::Camera build_camera(std::unordered_map<std::uint64_t, E::Camera> &history, std::uint64_t surface,
                               const CameraDesc &d) {
            E::Camera camera = history[surface];
            if (std::getenv("STURDY_LEGACY_CAMERA") != nullptr) {
                camera = d.projection == CameraProjection::Orthographic
                             ? E::Camera::orthographic(d.orthographic_size, d.aspect_ratio, d.near_clip, d.far_clip)
                             : E::Camera::perspective(d.vertical_fov_degrees, d.aspect_ratio, d.near_clip, d.far_clip);
                camera.set_position({d.position[0], d.position[1], d.position[2]});
                camera.set_euler_degrees({d.euler_degrees[0], d.euler_degrees[1], d.euler_degrees[2]});
                return camera;
            }
            sturdy_rs::camera::camera_apply_desc(camera, d);
            history[surface] = camera;
            history[surface].commit_frame();
            return camera;
        }

        E::SceneLighting build_lighting(const SceneLightingDesc &d) {
            E::SceneLighting lighting{};
            lighting.ambient_radiance = {d.ambient_radiance[0], d.ambient_radiance[1], d.ambient_radiance[2]};
            lighting.exposure = d.exposure;
            return lighting;
        }

        /// Registers the ECS -> renderer extraction systems, exactly as the engine's own C++ demo game
        /// logic does (`RuntimeDemoGameLogic::configure_render_extraction`). The engine runs the
        /// extraction schedule every frame but ships it empty: without these, `ModelRenderer`,
        /// `LightGizmoRenderer` and the light renderer components never reach the renderer, so
        /// spawned models and lights silently draw nothing.
        void configure_render_extraction(E::Engine &engine) {
            namespace Ecs = SFT::Ecs;
            engine.ecs_world().bind_resource(engine.render_frame_requests());
            engine.render_extraction_schedule().add_system(
                [](Ecs::Entity entity, const E::WorldTransform &transform, const E::ModelRenderer &model_renderer,
                   Ecs::WriteResource<E::RenderFrameRequests> render) noexcept {
                    render->submit(entity, transform, model_renderer);
                });
            engine.render_extraction_schedule().add_system(
                [](Ecs::Entity entity, const E::WorldTransform &transform, const E::LightGizmoRenderer &gizmo,
                   Ecs::WriteResource<E::RenderFrameRequests> render) noexcept {
                    render->submit_gizmo(entity, transform, gizmo);
                });
            engine.ecs_world().bind_resource(engine.light_frame_requests());
            engine.render_extraction_schedule().add_system(
                [](Ecs::Entity entity, const E::WorldTransform &transform, const E::DirectionalLightRenderer &light,
                   Ecs::WriteResource<E::LightFrameRequests> lights) noexcept {
                    lights->submit(entity, transform, light);
                });
            engine.render_extraction_schedule().add_system(
                [](Ecs::Entity entity, const E::WorldTransform &transform, const E::SpotLightRenderer &light,
                   Ecs::WriteResource<E::LightFrameRequests> lights) noexcept {
                    lights->submit(entity, transform, light);
                });
            engine.render_extraction_schedule().add_system(
                [](Ecs::Entity entity, const E::WorldTransform &transform, const E::PointLightRenderer &light,
                   Ecs::WriteResource<E::LightFrameRequests> lights) noexcept {
                    lights->submit(entity, transform, light);
                });
        }

        class RustGameLogic final : public E::GameLogic {
          public:
            explicit RustGameLogic(rust::Box<LogicHandle> logic) : logic_(std::move(logic)) {
            }

            E::GameLogicResult on_engine_initialized(E::Engine &engine) override {
                configure_render_extraction(engine);
                Status status = logic_on_init(*logic_, engine);
                if (status.ok) {
                    return {};
                }
                return std::unexpected(E::GameLogicError{to_ustring(status.message)});
            }

            std::optional<E::RenderFrameParameters> request_render_frame(
                E::Engine &engine,
                C::RenderSurfaceHandle surface,
                const C::FrameInput &frame) override {
                const FrameInfo info{
                    .delta_seconds = frame.delta_seconds,
                    .frame_index = frame.frame_index,
                    .framebuffer_width = frame.framebuffer_width,
                    .framebuffer_height = frame.framebuffer_height,
                    .live_resize = frame.live_resize,
                    .window_id = static_cast<std::uint64_t>(surface.window_id),
                };
                FrameRequest request = logic_request_frame(*logic_, engine, info);
                if (!request.present) {
                    return std::nullopt;
                }
                E::RenderFrameParameters params{};
                params.camera = build_camera(camera_history_, static_cast<std::uint64_t>(surface.window_id), request.camera);
                params.lighting = build_lighting(request.lighting);
                params.debug_label = to_ustring(request.debug_label);
                params.render_graph = sturdy_rs::render::consume_pending_render_graph();
                if (request.overlay_only) {
                    // A UI-only window: no G-buffer, lighting, bloom or tone mapping, just the overlay passes.
                    params.render_graph = E::RenderGraph::overlay_only();
                }

                // Builds this frame's UI overlay (a no-op if no draw hook is registered / the UI
                // renderer isn't ready yet) and attaches whatever it produced. See ui.rs's module
                // doc comment: this is the "remaining integration step" that doc used to describe as
                // future work -- it now lives here, right where a hand-written C++ caller would put
                // the `sturdy_ui_begin`/`sturdy_ui_end` pair FFI/Ui.cpp documents.
                // The UI is drawn into the linear RGBA16Float layer for HDR output, and for a UI-only frame on a transparent
                // surface; otherwise straight into the swapchain. Telling the UI renderer up front avoids building its
                // pipelines for one format and rebuilding them for the other on the first frame (the overlay still
                // corrects itself if the renderer decides differently, e.g. HDR the display refuses).
                const auto presentation = engine.presentation_settings(surface);
                const bool linear_layer = static_cast<bool>(presentation.hdr_enabled) ||
                                          (request.overlay_only && static_cast<bool>(presentation.transparent_composition));
                if (sturdy_rs::ui::ui_run_frame(engine, frame.framebuffer_width, frame.framebuffer_height,
                                                frame.delta_seconds, linear_layer)) {
                    if (auto overlay = sturdy_rs::ui::ui_take_pending_overlay()) {
                        params.overlay_passes.push_back(std::move(*overlay));
                    }
                }
                return params;
            }

            void on_shutdown(E::Engine &engine) noexcept override {
                logic_on_shutdown(*logic_, engine);
                // The shared UI holds a system in the engine's schedule and GPU objects on its device.
                E::release_foreign_ui();
            }

          private:
            rust::Box<LogicHandle> logic_;
            std::unordered_map<std::uint64_t, E::Camera> camera_history_;
        };

        std::unique_ptr<E::GameLogic> make_logic() {
            auto logic = std::move(*g_pending_logic);
            g_pending_logic.reset();
            return std::make_unique<RustGameLogic>(std::move(logic));
        }

