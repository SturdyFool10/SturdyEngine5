    UiBounds ui_element_bounds(rust::Str id) {
        UiBounds out{};
        if (!g_session.open) {
            return out;
        }
        if (const auto bounds = g_session.context->element_bounds(id_of(id))) {
            out.found = true;
            out.position = {bounds->position.x, bounds->position.y};
            out.size = {bounds->size.x, bounds->size.y};
        }
        return out;
    }
