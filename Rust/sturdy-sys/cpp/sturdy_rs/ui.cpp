        void reset_session() noexcept {
            // Destroyed innermost-first so each scope closes the element it opened, which is the
            // order the layout expects even when the draw hook left elements unbalanced.
            while (!g_session.open_elements.empty()) {
                g_session.open_elements.pop_back();
            }
            g_session.open = false;
            g_session.context = nullptr;
        }

