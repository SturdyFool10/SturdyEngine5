        std::vector<glm::vec2> to_points(rust::Slice<const float> flat) {
            std::vector<glm::vec2> points;
            points.reserve(flat.size() / 2);
            for (std::size_t i = 0; i + 1 < flat.size(); i += 2) {
                points.emplace_back(flat[i], flat[i + 1]);
            }
            return points;
        }

