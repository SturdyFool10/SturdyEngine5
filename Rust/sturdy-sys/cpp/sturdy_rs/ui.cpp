    UiSvgOutcome ui_load_svg(EngineView &engine, rust::Str path, float target_px) {
        UiSvgOutcome outcome{};
        try {
            const std::filesystem::path source{std::string{path.data(), path.size()}};
            const auto result = engine.ui_svg_cache().resolve(engine.assets(), source, target_px);
            if (!result) {
                const auto view = result.error().message.cpp_string_view();
                outcome.ok = false;
                outcome.message = rust::String::lossy(view.data(), view.size());
                return outcome;
            }
            outcome.ok = true;
            outcome.texture = UiTexture{result->value};
            return outcome;
        } catch (const std::exception &e) {
            outcome.ok = false;
            outcome.message = rust::String::lossy(e.what());
            return outcome;
        } catch (...) {
            outcome.ok = false;
            outcome.message = rust::String{"an unexpected C++ exception was caught at the FFI boundary"};
            return outcome;
        }
    }

