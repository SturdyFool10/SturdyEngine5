    bool ui_graph(const UiElementDesc &desc, const UiGraphDesc &graph) {
        if (!g_session.open) {
            return false;
        }
        try {
            SFT::UI::GraphDesc out{};
            switch (graph.graph_type) {
            case UiGraphType::Area: out.type = SFT::UI::GraphType::Area; break;
            case UiGraphType::Bar: out.type = SFT::UI::GraphType::Bar; break;
            case UiGraphType::Scatter: out.type = SFT::UI::GraphType::Scatter; break;
            case UiGraphType::Pie: out.type = SFT::UI::GraphType::Pie; break;
            case UiGraphType::Line:
            default: out.type = SFT::UI::GraphType::Line; break;
            }
            out.x_axis = to_engine(graph.x_axis);
            out.y_axis = to_engine(graph.y_axis);
            // SeriesRef borrows x/y as spans; `graph` (and its rust::Vecs) outlives this call.
            out.series.reserve(graph.series.size());
            for (const UiGraphSeries &series : graph.series) {
                SFT::UI::SeriesRef ref{};
                ref.name = to_std(series.name);
                ref.x = std::span<const double>{series.x.data(), series.x.size()};
                ref.y = std::span<const double>{series.y.data(), series.y.size()};
                ref.color = to_engine_color(series.color);
                ref.line_width = series.line_width;
                ref.feather_px = series.feather_px;
                ref.area_fill_opacity = series.area_fill_opacity;
                ref.marker_radius = series.marker_radius;
                ref.glow_intensity = series.glow_intensity;
                out.series.push_back(std::move(ref));
            }
            out.bar_stack_mode = graph.bar_stack_mode == UiBarStackMode::Stacked ? SFT::UI::BarStackMode::Stacked
                                                                                 : SFT::UI::BarStackMode::Grouped;
            out.bar_group_gap_fraction = graph.bar_group_gap_fraction;
            out.bar_series_gap_fraction = graph.bar_series_gap_fraction;
            out.pie_slices.reserve(graph.pie_slices.size());
            for (const UiPieSlice &slice : graph.pie_slices) {
                out.pie_slices.push_back(SFT::UI::PieSlice{to_std(slice.name), slice.value, to_engine_color(slice.color)});
            }
            out.pie_style.hole_ratio = graph.pie_hole_ratio;
            out.pie_style.start_angle_degrees = graph.pie_start_angle_degrees;
            out.pie_style.gap_degrees = graph.pie_gap_degrees;
            out.pie_style.feather_px = graph.pie_feather_px;
            out.background_color = to_engine_color(graph.background);
            out.corner_radius = SFT::UI::CornerRadius{graph.corner_radius[0], graph.corner_radius[1],
                                                      graph.corner_radius[2], graph.corner_radius[3]};
            out.axis_margin_left = graph.axis_margins[0];
            out.axis_margin_bottom = graph.axis_margins[1];
            out.axis_margin_top = graph.axis_margins[2];
            out.axis_margin_right = graph.axis_margins[3];
            out.font_id = static_cast<SFT::UI::FontId>(graph.font_id);
            out.label_font_size = graph.label_font_size;
            out.title_font_size = graph.title_font_size;
            out.show_legend = graph.show_legend;

            SFT::UI::GraphState state{};
            return SFT::UI::graph(*g_session.context, to_element_decl(desc), out, state).drawn;
        } catch (...) {
            return false;
        }
    }

