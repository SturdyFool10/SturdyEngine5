RUST_KEYWORDS = set("""as break const continue crate else enum extern false fn for if impl in let loop match mod move mut pub ref return
self Self static struct super trait true type unsafe use where while async await dyn abstract become box do final macro override priv
typeof unsized virtual yield try gen""".split())


def rust_ident(name):
    return "r#" + name if name in RUST_KEYWORDS and name not in ("self", "Self", "super", "crate") else (name + "_" if name in ("self", "Self", "super", "crate") else name)


def emit_rust(api: Api) -> str:
    """Raw `#[repr(C)]` structs, `i32` enums with constants, callback aliases and one `extern "C"` declaration per function.

    The functions are declared, not linked: nothing here names a library, so a plugin (a `cdylib` loaded by the engine) leaves them
    undefined and the dynamic loader resolves them against the engine's own copy, and an executable links `-lsturdy` itself. Every
    struct is followed by compile-time size, alignment and offset assertions computed from the C layout rules, so a Rust compiler that
    lays a struct out differently fails the build instead of corrupting memory.
    """
    out = []
    w = out.append

    def rtype(t):
        k = t["kind"]
        if k == "void":
            return "()"
        if k == "bool":
            return "bool"
        if k == "char":
            return "c_char"
        if k == "int":
            return f"{'i' if t['signed'] else 'u'}{t['width']}"
        if k == "float":
            return "f32" if t["width"] == 32 else "f64"
        if k == "enum":
            return "i32"
        if k == "struct":
            return t["name"]
        if k == "callback":
            return f"Option<{t['name']}>"
        if k == "function_pointer":
            return f"Option<{rfn(t['ret'], t['params'])}>"
        if k == "array":
            return f"[{rtype(t['of'])}; {t['count']}]"
        if k == "pointer":
            to = t["to"]
            mut = "*const" if t.get("const") else "*mut"
            if to["kind"] == "void":
                return f"{mut} c_void"
            if to["kind"] == "callback":
                return f"{mut} {to['name']}"
            if to["kind"] == "function_pointer":
                return f"{mut} {rfn(to['ret'], to['params'])}"
            return f"{mut} {rtype(to)}"
        raise ValueError(t)

    def rfn(ret, params):
        args = ", ".join(rtype(p) for p in params)
        r = "" if ret["kind"] == "void" else f" -> {rtype(ret)}"
        return f'unsafe extern "C" fn({args}){r}'

    w("// " + BANNER)
    w("//")
    w("// Raw declarations for the Sturdy Engine C ABI. Nothing is linked from here: a plugin leaves the functions undefined for the")
    w("// engine's shared library to satisfy at load time; an executable links the library itself. Enums are `i32` plus constants (C enums")
    w("// admit values Rust's `enum` must not), callbacks are `Option<unsafe extern \"C\" fn ...>`, and every struct is checked at compile")
    w("// time against the C layout rules. For a safe layer see `sturdy-plugin`.")
    w("#![allow(non_camel_case_types, non_upper_case_globals, non_snake_case, dead_code, clippy::all)]")
    w("")
    w("use core::ffi::{c_char, c_void};")
    w("")
    w(f"pub const ABI_VERSION_MAJOR: u32 = {api.version['major']};")
    w(f"pub const ABI_VERSION_MINOR: u32 = {api.version['minor']};")
    w("")
    for e in api.d["enums"]:
        for line in doc_lines(clean(e["doc"]), "", "/// "):
            w(line)
        w(f"pub type {e['name']} = i32;")
        for v in e["values"]:
            w(f"pub const {v['name']}: {e['name']} = {v['value']};")
        w("")
    for c in api.d["callbacks"]:
        for line in doc_lines(clean(c["doc"]), "", "/// "):
            w(line)
        w(f"pub type {c['name']} = {rfn(c['ret'], [p['type'] for p in c['params']])};")
        w("")
    for name in api.struct_order():
        s = api.structs[name]
        for line in doc_lines(clean(s["doc"]), "", "/// "):
            w(line)
        w("#[repr(C)]")
        w("#[derive(Clone, Copy)]")
        w(f"pub struct {name} {{")
        for f in s["fields"]:
            w(f"    pub {rust_ident(f['name'])}: {rtype(f['type'])},")
        w("}")
        w(f"impl Default for {name} {{")
        w("    /// All zero: null pointers, absent callbacks, zero numbers. Set `struct_size` where the struct has one.")
        w("    fn default() -> Self {")
        w("        unsafe { core::mem::zeroed() }")
        w("    }")
        w("}")
        layout = api.layout(name)
        w(f"const _: () = assert!(core::mem::size_of::<{name}>() == {layout['size']} && core::mem::align_of::<{name}>() == {layout['align']});")
        for f in layout["fields"]:
            w(f"const _: () = assert!(core::mem::offset_of!({name}, {rust_ident(f['name'])}) == {f['offset']});")
        w("")
    w('unsafe extern "C" {')
    for fn in api.functions:
        for line in doc_lines(clean(fn["doc"]).strip(), "    ", "/// "):
            w(line)
        params = ", ".join(f"{rust_ident(p['name'])}: {rtype(p['type'])}" for p in fn["params"])
        ret = "" if fn["ret"]["kind"] == "void" else f" -> {rtype(fn['ret'])}"
        w(f"    pub fn {fn['name']}({params}){ret};")
    w("}")
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--api", required=True, type=Path)
    parser.add_argument("--python", type=Path)
    parser.add_argument("--java", type=Path)
    parser.add_argument("--csharp", type=Path)
    parser.add_argument("--rust", type=Path)
    parser.add_argument("--layout-check", type=Path, help="write a C program that prints the real sizeof/offsetof of every struct")
    parser.add_argument("--header-include", default="FFI/Sturdy.h")
    args = parser.parse_args()

    api = Api(json.loads(args.api.read_text(encoding="utf-8")))
    jobs = [(args.python, emit_python), (args.java, emit_java), (args.csharp, emit_csharp), (args.rust, emit_rust)]
    for path, emit in jobs:
        if path:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(emit(api), encoding="utf-8")
            print(f"wrote {path}")
    if args.layout_check:
        args.layout_check.parent.mkdir(parents=True, exist_ok=True)
        args.layout_check.write_text(emit_layout_check(api, args.header_include), encoding="utf-8")
        print(f"wrote {args.layout_check}")


if __name__ == "__main__":
    main()
