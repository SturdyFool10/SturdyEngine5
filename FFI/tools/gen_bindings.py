JAVA_KEYWORDS = set("""abstract assert boolean break byte case catch char class const continue default do double else enum extends final
finally float for goto if implements import instanceof int interface long native new package private protected public return short static
strictfp super switch synchronized this throw throws transient try void volatile while var record yield sealed permits true false null""".split())


def java_ident(name):
    return name + "_" if name in JAVA_KEYWORDS else name


def emit_java(api: Api) -> str:
    out = []
    w = out.append

    def layout(t):
        k = t["kind"]
        if k == "void":
            return None
        if k == "bool":
            return "ValueLayout.JAVA_BOOLEAN"
        if k == "char":
            return "ValueLayout.JAVA_BYTE"
        if k == "int":
            return {8: "ValueLayout.JAVA_BYTE", 16: "ValueLayout.JAVA_SHORT", 32: "ValueLayout.JAVA_INT", 64: "ValueLayout.JAVA_LONG"}[t["width"]]
        if k == "float":
            return "ValueLayout.JAVA_FLOAT" if t["width"] == 32 else "ValueLayout.JAVA_DOUBLE"
        if k == "enum":
            return "ValueLayout.JAVA_INT"
        if k in ("pointer", "function_pointer", "callback"):
            return "ValueLayout.ADDRESS"
        if k == "struct":
            return t["name"].upper() + "_LAYOUT" if False else f"LAYOUT_{t['name']}"
        if k == "array":
            return f"MemoryLayout.sequenceLayout({t['count']}, {layout(t['of'])})"
