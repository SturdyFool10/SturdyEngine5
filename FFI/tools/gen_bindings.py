CSHARP_KEYWORDS = set("""abstract as base bool break byte case catch char checked class const continue decimal default delegate do double else
enum event explicit extern false finally fixed float for foreach goto if implicit in int interface internal is lock long namespace new null
object operator out override params private protected public readonly ref return sbyte sealed short sizeof stackalloc static string struct
switch this throw true try typeof uint ulong unchecked unsafe ushort using virtual void volatile while""".split())


def cs_ident(name):
    return "@" + name if name in CSHARP_KEYWORDS else name


def emit_csharp(api: Api) -> str:
    out = []
    w = out.append

    def cstype(t):
        k = t["kind"]
        if k == "void":
            return "void"
        if k == "bool":
            return "byte"  # the ABI's bool is one byte; marshalling it as `bool` would make the CLR assume four
        if k == "char":
            return "byte"
        if k == "int":
            return {(8, True): "sbyte", (8, False): "byte", (16, True): "short", (16, False): "ushort", (32, True): "int",
                    (32, False): "uint", (64, True): "long", (64, False): "ulong"}[(t["width"], t["signed"])]
        if k == "float":
            return "float" if t["width"] == 32 else "double"
        if k == "enum":
            return t["name"]
        if k == "struct":
            return t["name"]
        if k == "callback":
            return cs_fnptr(api.callbacks[t["name"]]["ret"], [p["type"] for p in api.callbacks[t["name"]]["params"]])
        if k == "function_pointer":
            return cs_fnptr(t["ret"], t["params"])
        if k == "pointer":
            to = t["to"]
            if to["kind"] == "void":
                return "void*"
            if to["kind"] == "callback" or to["kind"] == "function_pointer":
                return cstype(to) + "*"
            return cstype(to) + "*"
        raise ValueError(t)

    def cs_fnptr(ret, params):
        return "delegate* unmanaged[Cdecl]<" + ", ".join([cstype(p) for p in params] + [cstype(ret)]) + ">"

    w("// " + BANNER)
    w("//")
    w("// P/Invoke with unsafe code (C# 9 function pointers): compile with AllowUnsafeBlocks. Callbacks are `delegate* unmanaged[Cdecl]`, which you")
    w("// obtain from a static method marked [UnmanagedCallersOnly(CallConvs = new[] { typeof(CallConvCdecl) })]. The ABI's bool is one byte, so it")
    w("// appears as `byte` (0 or 1). NOTE: generated and kept in step with the header, but not compiled in this repository's CI (no .NET toolchain).")
    w("#nullable disable")
    w("using System;")
    w("using System.Runtime.InteropServices;")
    w("")
    w("namespace Sturdy")
    w("{")
    w(f"    public static class AbiVersion {{ public const uint Major = {api.version['major']}; public const uint Minor = {api.version['minor']}; }}")
    w("")
    for e in api.d["enums"]:
        for line in doc_lines(clean(e["doc"]), "    ", "/// "):
            w(line)
        w(f"    public enum {e['name']} : int")
        w("    {")
        for v in e["values"]:
            w(f"        {v['name']} = {v['value']},")
        w("    }")
        w("")
    for name in api.struct_order():
        s = api.structs[name]
        for line in doc_lines(clean(s["doc"]), "    ", "/// "):
            w(line)
        w("    [StructLayout(LayoutKind.Sequential)]")
        w(f"    public unsafe struct {name}")
        w("    {")
        for f in s["fields"]:
            t = f["type"]
            if t["kind"] == "array":
                base = t["of"]
                if base["kind"] in ("int", "float", "bool", "char"):
                    w(f"        public fixed {cstype(base)} {cs_ident(f['name'])}[{t['count']}];")
                else:
                    # Arrays of structs or pointers cannot be `fixed` buffers: expand to numbered fields (same memory layout).
                    for i in range(t["count"]):
                        w(f"        public {cstype(base)} {cs_ident(f['name'])}_{i};")
            else:
                w(f"        public {cstype(t)} {cs_ident(f['name'])};")
        w("    }")
        w("")
    w('    public static unsafe partial class Native')
    w("    {")
    w('        /// <summary>The native library name; resolved by the runtime (libsturdy.so, sturdy.dll, libsturdy.dylib).</summary>')
    w('        public const string Library = "sturdy";')
    for fn in api.functions:
        w("")
        for line in doc_lines(clean(fn["doc"]).strip(), "        ", "/// "):
            w(line)
        w("        [DllImport(Library, CallingConvention = CallingConvention.Cdecl)]")
        params = ", ".join(f"{cstype(p['type'])} {cs_ident(p['name'])}" for p in fn["params"])
        w(f"        public static extern {cstype(fn['ret'])} {fn['name']}({params});")
    w("    }")
    w("}")
    return "\n".join(out) + "\n"


