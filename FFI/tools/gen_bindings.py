    w("        int minor = sturdy_abi_version_minor();")
    w("        if (major != ABI_MAJOR || minor < ABI_MINOR) {")
    w("            throw new IllegalStateException(\"the library implements ABI \" + major + \".\" + minor + \"; this binding needs \" + ABI_MAJOR + \".\" + ABI_MINOR + \" or a later minor\");")
    w("        }")
    w("    }")
    w("")
    w("    private static MethodHandle handle(String name, FunctionDescriptor descriptor) {")
    w("        return HANDLES.computeIfAbsent(name, n -> LINKER.downcallHandle(")
    w("                lookup.find(n).orElseThrow(() -> new UnsatisfiedLinkError(n + \" is not exported by the loaded library\")), descriptor));")
    w("    }")
    w("")
    w("    // ---- functions ----")
    for fn in api.functions:
        ret = fn["ret"]
        args = [layout(p["type"]) for p in fn["params"]]
        rl = layout(ret)
        desc = f"FunctionDescriptor.of({', '.join([rl] + args)})" if rl else f"FunctionDescriptor.ofVoid({', '.join(args)})"
        params = [f"{jtype(p['type'])} {java_ident(p['name'])}" for p in fn["params"]]
        call_args = [java_ident(p["name"]) for p in fn["params"]]
        struct_ret = ret["kind"] == "struct"
        if struct_ret:
            params = ["SegmentAllocator allocator"] + params
            call_args = ["allocator"] + call_args
        jret = jtype(ret)
        cast = f"({jret}) " if jret != "void" else ""
        w("")
        for line in doc_lines(clean(fn["doc"]).strip(), "    ", "// "):
            w(line)
        w(f"    public static {jret} {fn['name']}({', '.join(params)}) throws Throwable {{")
        w(f"        MethodHandle h = handle(\"{fn['name']}\", {desc});")
        w(f"        {'return ' if jret != 'void' else ''}{cast}h.invokeExact({', '.join(call_args)});")
        w("    }")
    w("}")
    return "\n".join(out) + "\n"


