    w("//")
    w("// Panama (java.lang.foreign, Java 22 or later). C `uint32_t` is Java `int` and `uint64_t`/`size_t` is `long`: Java has no unsigned types, so")
    w("// compare with Integer.toUnsignedLong / Long.compareUnsigned where it matters. Pointers and structs passed by value are MemorySegments.")
