#!/usr/bin/env python3
"""Generates language bindings for the C ABI from its JSON description (`describe_abi.py`).

    gen_bindings.py --api FFI/api/sturdy_abi.json --python FFI/bindings/python/sturdy.py \
                    --java FFI/bindings/java/dev/sturdy/Sturdy.java --csharp FFI/bindings/csharp/Sturdy.cs \
                    --layout-check FFI/tools/layout_check.c

Every binding is a mechanical translation of the same description, so a function added to `Sturdy.h` appears in every language after
re-running the two tools, and a binding can never disagree with another about a type. Struct layout is computed here from the C rules
(natural alignment; the header has no packing or bit-fields) and cross-checked by `layout_check.c`, which prints the real
`sizeof`/`offsetof` from the real header so a test can compare them with what each binding believes.

What each target gives you:
  python  ctypes: structs, IntEnum enums, callback types, a lazily bound `Library`, and `check()` which raises on a failed result.
  java    Panama (java.lang.foreign, Java 22+): struct layouts and field offsets, enum constants, one static method per function,
          and a FunctionDescriptor per callback for `Linker.upcallStub`.
  csharp  P/Invoke with unsafe code: sequential structs, enums, `delegate* unmanaged` function pointers, one extern per function.
          (Generated and kept in step, but not compiled in this repository's CI: there is no .NET toolchain on the build machines.)
"""

