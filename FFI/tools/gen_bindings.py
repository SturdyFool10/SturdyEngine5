    w("    // ---- callbacks: descriptors for Linker.upcallStub ----")
    for c in api.d["callbacks"]:
        args = [layout(p["type"]) for p in c["params"]]
        ret = layout(c["ret"])
        desc = f"FunctionDescriptor.of({', '.join([ret] + args)})" if ret else f"FunctionDescriptor.ofVoid({', '.join(args)})"
