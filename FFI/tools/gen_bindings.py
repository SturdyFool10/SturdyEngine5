class Api:
    def __init__(self, description):
        self.d = description
        self.version = description["abi_version"]
        self.enums = {e["name"]: e for e in description["enums"]}
        self.structs = {s["name"]: s for s in description["structs"]}
        self.callbacks = {c["name"]: c for c in description["callbacks"]}
        self.functions = description["functions"]
        self._layouts = {}

    def size_align(self, t):
        """(size, alignment) in bytes of a described type, by the C rules for a 64-bit target."""
        k = t["kind"]
        if k == "int" or k == "float":
            w = t["width"] // 8
            return w, w
        if k == "bool" or k == "char":
            return 1, 1
        if k == "enum":
            return 4, 4
        if k in ("pointer", "function_pointer", "callback"):
            return 8, 8
        if k == "array":
            s, a = self.size_align(t["of"])
            return s * t["count"], a
        if k == "struct":
            layout = self.layout(t["name"])
            return layout["size"], layout["align"]
        raise ValueError(f"no size for type {t}")

    def layout(self, name):
        if name in self._layouts:
            return self._layouts[name]
        offset, align, fields = 0, 1, []
        for f in self.structs[name]["fields"]:
            size, a = self.size_align(f["type"])
            offset = (offset + a - 1) // a * a
            fields.append({"name": f["name"], "offset": offset, "size": size, "align": a})
            offset += size
            align = max(align, a)
        size = (offset + align - 1) // align * align
        self._layouts[name] = {"size": size, "align": align, "fields": fields}
        return self._layouts[name]

    def struct_order(self):
        """Structs so that every struct appears after the structs it contains by value."""
        done, order = set(), []

        def visit(name):
            if name in done:
                return
            done.add(name)
            for f in self.structs[name]["fields"]:
                t = f["type"]
                while t["kind"] == "array":
                    t = t["of"]
                if t["kind"] == "struct":
                    visit(t["name"])
            order.append(name)

        for name in sorted(self.structs):
            visit(name)
        return order


def doc_lines(text, indent, prefix="/// "):
    if not text:
        return []
    out = []
    for line in text.replace("\r", "").split("\n"):
        out.append(f"{indent}{prefix}{line}".rstrip())
    return out


def clean(text):
    """Doc text safe to place inside a comment of any language."""
    return (text or "").replace("*/", "* /").replace("\\", "/")


BANNER = "Generated by FFI/tools/gen_bindings.py from FFI/api/sturdy_abi.json. Do not edit: change Sturdy.h and re-run the tools."


