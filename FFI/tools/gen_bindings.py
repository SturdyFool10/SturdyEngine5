def emit_layout_check(api: Api, header_include: str) -> str:
    out = ["/* " + BANNER + " */", f"#include <{header_include}>", "#include <stddef.h>", "#include <stdio.h>", "", "int main(void) {"]
    for name in sorted(api.structs):
        out.append(f'    printf("{name} %zu %zu", sizeof({name}), _Alignof({name}));')
        for f in api.structs[name]["fields"]:
            out.append(f'    printf(" {f["name"]}=%zu", offsetof({name}, {f["name"]}));')
        out.append('    printf("\\n");')
    out += ["    return 0;", "}"]
    return "\n".join(out) + "\n"


