    w(f"    public static final int ABI_MAJOR = {api.version['major']};")
    w(f"    public static final int ABI_MINOR = {api.version['minor']};")
    w("")
    w("    private Sturdy() {}")
    w("")
    w("    // ---- enums (C enums are 32-bit) ----")
